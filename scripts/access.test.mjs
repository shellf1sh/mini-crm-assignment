import assert from 'node:assert/strict'
import { test } from 'node:test'
import { randomBytes } from 'node:crypto'
import { client, ok, config, signIn, siteArgs, taskArgs, transitionArgs, readDemo } from './common.mjs'

test('Supabase enforces roles, task state and audit history over the Data API', async () => {
  const { url, key, file } = config()
  const [manager, a, b] = await Promise.all(readDemo(file).map(account => signIn(url, key, account)))
  const anonymous = client(url, key)
  const authSettings = await fetch(url + '/auth/v1/settings', { headers: { apikey: key } })
  assert.equal(authSettings.ok, true)
  assert.equal((await authSettings.json()).disable_signup, true)
  const tag = 'API check ' + randomBytes(4).toString('hex')
  const sites = [], tasks = []
  const denied = async (response, code) => {
    const { error } = await response
    assert.ok(error, 'operation should fail')
    if (code) assert.equal(error.code, code)
  }
  const rows = async (db, table, id) => ok(await db.from(table).select('*').eq('id', id))
  const history = async (db, id) => ok(await db.from('task_history').select('*').eq('task_id', id).order('id'))
  const move = (actor, task, prev, next, note) => actor.db.rpc('transition_task', transitionArgs(task, prev, next, note))
  try {
    await denied(anonymous.from('tasks').select('*'), '42501')
    await denied(anonymous.rpc('save_object', siteArgs(tag, 'No')), '42501')
    await denied(a.db.rpc('save_object', siteArgs(tag, 'No')), '42501')
    const ownSite = ok(await manager.db.rpc('save_object', siteArgs(tag, 'Test address')))
    sites.push(ownSite)
    const otherSite = ok(await manager.db.rpc('save_object', siteArgs(tag + ' other', 'Test address')))
    sites.push(otherSite)
    const own = ok(await manager.db.rpc('save_task', taskArgs(ownSite, a.id, tag, 'Description')))
    tasks.push(own)
    const other = ok(await manager.db.rpc('save_task', taskArgs(otherSite, b.id, tag, 'Description')))
    tasks.push(other)
    const sameSiteOther = ok(await manager.db.rpc('save_task', taskArgs(ownSite, b.id, tag + ' shared site', 'Description')))
    tasks.push(sameSiteOther)
    assert.equal((await rows(a.db, 'objects', ownSite)).length, 1)
    assert.deepEqual(await rows(a.db, 'objects', otherSite), [])
    assert.deepEqual(await rows(a.db, 'tasks', other), [])
    assert.deepEqual(await rows(a.db, 'tasks', sameSiteOther), [])
    assert.deepEqual(await rows(b.db, 'tasks', own), [])
    assert.deepEqual(await history(b.db, own), [])
    assert.equal((await history(manager.db, other)).length, 1)
    assert.equal((await history(a.db, own))[0].actor_id, manager.id)
    await denied(a.db.from('tasks').update({ status: 'accepted', assignee_id: b.id }).eq('id', own), '42501')
    await denied(manager.db.from('tasks').update({ status: 'accepted' }).eq('id', own), '42501')
    await denied(a.db.from('profiles').update({ role: 'manager' }).eq('id', a.id), '42501')
    await denied(a.db.rpc('archive_task', { p_id: own }), '42501')
    await denied(a.db.rpc('save_task', taskArgs(ownSite, b.id, 'Changed', '', own)), '42501')
    await denied(manager.db.rpc('save_task', taskArgs(ownSite, manager.id, 'Invalid executor', '')))
    await denied(manager.db.rpc('archive_object', { p_id: ownSite }))
    await denied(move(a, other, 'new', 'in_progress'), '42501')
    await denied(move(manager, own, 'new', 'in_progress'), '42501')
    await denied(move(a, own, 'new', 'in_review'), '42501')
    const concurrent = await Promise.all([move(a, own, 'new', 'in_progress'), move(a, own, 'new', 'in_progress')])
    assert.equal(concurrent.filter(r => !r.error).length, 1)
    assert.equal((await history(a.db, own)).length, 2)
    ok(await move(a, own, 'in_progress', 'in_review'))
    await denied(move(a, own, 'in_review', 'accepted'), '42501')
    await denied(move(manager, own, 'in_review', 'revision', ' \n\t '), '22023')
    await denied(move(manager, own, 'in_review', 'revision', 'a'.repeat(1501)), '23514')
    assert.equal((await rows(a.db, 'tasks', own))[0].status, 'in_review')
    assert.equal((await history(a.db, own)).length, 3)
    ok(await move(manager, own, 'in_review', 'revision', 'Please check the plan'))
    ok(await move(a, own, 'revision', 'in_progress'))
    ok(await move(a, own, 'in_progress', 'in_review'))
    ok(await move(manager, own, 'in_review', 'accepted'))
    assert.equal((await rows(a.db, 'tasks', own))[0].status, 'accepted')
    const records = await history(a.db, own)
    assert.deepEqual(records.map(r => r.new_status), ['new', 'in_progress', 'in_review', 'revision', 'in_progress', 'in_review', 'accepted'])
    assert.equal(records[3].comment, 'Please check the plan')
    assert.equal(records[3].actor_id, manager.id)
    for (const actor of [a, manager]) {
      await denied(actor.db.from('task_history').insert({ task_id: own, actor_id: actor.id, actor_name: 'Fake', new_status: 'new' }), '42501')
      await denied(actor.db.from('task_history').update({ comment: 'Fake' }).eq('id', records[0].id), '42501')
      await denied(actor.db.from('task_history').delete().eq('id', records[0].id), '42501')
    }
    assert.deepEqual(await history(a.db, own), records)
    ok(await manager.db.rpc('save_task', taskArgs(ownSite, b.id, tag, 'Reassigned', own)))
    assert.deepEqual(await rows(a.db, 'tasks', own), [])
    assert.deepEqual(await history(a.db, own), [])
    assert.equal((await history(b.db, own)).length, records.length)
    assert.equal((await rows(b.db, 'tasks', own))[0].status, 'accepted')
    assert.deepEqual(await rows(a.db, 'objects', ownSite), [])
  } finally {
    for (const id of tasks) ok(await manager.db.rpc('archive_task', { p_id: id }))
    for (const id of sites) ok(await manager.db.rpc('archive_object', { p_id: id }))
    for (const id of tasks) assert.deepEqual(await rows(manager.db, 'tasks', id), [])
    for (const id of sites) assert.deepEqual(await rows(manager.db, 'objects', id), [])
  }
})
